#!/usr/bin/env node
/**
 * Publishes EffectPlan's CI definition where GitHub Actions can read it.
 *
 * GitHub only runs workflows that live in `.github/workflows` at the *root* of
 * the repository. This project lives in a subdirectory of a shared repository, so
 * `EffectPlan/.github/workflows/ci.yml` — which is the file a reader of this
 * directory finds, edits and reviews — is invisible to a runner unless it is
 * mirrored to the repository root. This script writes that mirror; it changes the
 * triggers, the working directory and the name, and it changes no job.
 *
 *   node scripts/sync-ci.mjs            # write the root workflow
 *   node scripts/sync-ci.mjs --check    # fail if the mirror is stale
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, ".github", "workflows", "ci.yml");
// One level up is the repository root, because this project is a subdirectory.
const TARGET = path.join(ROOT, "..", ".github", "workflows", "effectplan-ci.yml");

// Git may hand back CRLF line endings on Windows checkouts, and the mirror must
// not depend on which operating system wrote it.
const text = readFileSync(SOURCE, "utf8").replaceAll("\r\n", "\n");
if (!text.startsWith("name: ci\n")) {
  process.stderr.write(`sync-ci: unexpected header in ${SOURCE}\n`);
  process.exit(1);
}

const jobs = text.slice(text.indexOf("jobs:\n"));
if (jobs.length === 0) {
  process.stderr.write("sync-ci: the source workflow declares no jobs\n");
  process.exit(1);
}

const header = `# Generated by EffectPlan/scripts/sync-ci.mjs - do not edit here.
#
# GitHub Actions only reads workflows from this directory, and EffectPlan lives
# one level down, so the project's real definition is
# EffectPlan/.github/workflows/ci.yml and this is a mirror of it with the
# triggers scoped to that subtree and every run command given a working
# directory. Re-run the script after editing the source, or --check fails.
name: effectplan-ci

on:
  pull_request:
    paths:
      - "EffectPlan/**"
      - ".github/workflows/effectplan-ci.yml"
  push:
    branches: [main]
    paths:
      - "EffectPlan/**"
      - ".github/workflows/effectplan-ci.yml"

permissions:
  contents: read

concurrency:
  group: effectplan-ci-\${{ github.ref }}
  cancel-in-progress: true

defaults:
  run:
    working-directory: EffectPlan

`;

const generated = header + jobs;

if (process.argv.includes("--check")) {
  if (!existsSync(TARGET)) {
    process.stderr.write(`sync-ci: ${TARGET} does not exist\n`);
    process.exit(1);
  }
  if (readFileSync(TARGET, "utf8").replaceAll("\r\n", "\n") !== generated) {
    process.stderr.write(
      `sync-ci: ${path.relative(ROOT, TARGET)} is stale; run "node scripts/sync-ci.mjs"\n`,
    );
    process.exit(1);
  }
  process.stdout.write("sync-ci: the repository-root workflow matches the project definition\n");
  process.exit(0);
}

mkdirSync(path.dirname(TARGET), { recursive: true });
writeFileSync(TARGET, generated, "utf8");
process.stdout.write(`sync-ci: wrote ${path.relative(ROOT, TARGET)}\n`);
