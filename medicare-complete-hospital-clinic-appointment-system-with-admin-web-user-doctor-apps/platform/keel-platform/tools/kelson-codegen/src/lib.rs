mod tests {
    use super::*;
    use kelson_context::{PrincipalContext, TenantContext};
    use kelson_foundation::{PrincipalId, TenantId};
    use kelson_execution::{
        AuthzDecision, AuthzRequest, AuthorizationPort, Engine, InMemoryBackend,
        InMemoryIdempotency,
    };
    use time::OffsetDateTime;

    struct AllowAll;
    impl AuthorizationPort for AllowAll {
        fn authorize(
            &self,
            _ctx: &ExecutionContext,
            _request: &AuthzRequest<'_>,
        ) -> AuthzDecision {
            AuthzDecision::allow("test.allow-all")
        }
    }

    #[tokio::test]
    async fn ping_executes_through_engine() {
        let engine = Engine::new(
            Arc::new(AllowAll),
            Arc::new(InMemoryBackend::new()),
            Arc::new(InMemoryIdempotency::new()),
        );
        let ctx = ExecutionContext::builder(ExecutionProfileKind::Read, OffsetDateTime::now_utc())
            .principal(PrincipalContext { id: PrincipalId::new(), display: None })
            .tenant(TenantContext { id: TenantId::new(), slug: "t".into(), plan: "standard".into() })
            .build()
            .unwrap();
        let handler = PingHandler::new();
        let outcome = engine.execute(ctx, &handler, serde_json::json!({}), None).await.unwrap();
        assert_eq!(outcome.result["pong"], serde_json::json!(true));
    }
}
