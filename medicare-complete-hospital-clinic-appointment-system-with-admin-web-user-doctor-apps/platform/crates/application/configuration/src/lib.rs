//! # keel-config
//! Typed configuration with deterministic layering (11-SPEC §19):
//! `defaults <- config file <- .env <- .env.<env> <- environment` (item 18).
//! Secrets are asserted at boot and are never silently defaulted outside dev.

pub mod dotenv;
pub mod keys;

use keel_foundation::AppError;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
#[derive(Default)]
pub enum Environment {
    #[default]
    Dev,
    Test,
    Staging,
    Prod,
}

impl Environment {
    pub fn is_prod(&self) -> bool {
        matches!(self, Environment::Prod)
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            Environment::Dev => "dev",
            Environment::Test => "test",
            Environment::Staging => "staging",
            Environment::Prod => "prod",
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AppConfig {
    #[serde(default = "default_name")]
    pub name: String,
    #[serde(default)]
    pub env: Environment,
    #[serde(default = "default_listen")]
    pub listen: String,
    /// Application key (item 18): base64-encoded secret material for app-level
    /// signing/encryption. Generated by `keel key:generate`; asserted in prod.
    #[serde(default)]
    pub key: String,
    /// B-23: gate module operations until the principal's email is verified.
    /// Auth endpoints stay open so verification can complete.
    #[serde(default)]
    pub require_verified_email: bool,
    /// Wave 2 dev-only debug detail gate: error responses carry redacted
    /// internal context only when true (19-PARITY "Error rendering").
    /// Defaults to false and is turned on explicitly in config/dev.toml;
    /// secrets are never rendered regardless of this flag.
    #[serde(default)]
    pub debug: bool,
}

fn default_name() -> String {
    "keel".into()
}
fn default_listen() -> String {
    "127.0.0.1:8180".into()
}

impl Default for AppConfig {
    fn default() -> Self {
        Self {
            name: default_name(),
            env: Environment::Dev,
            listen: default_listen(),
            key: String::new(),
            require_verified_email: false,
            debug: false,
        }
    }
}

