/// Mask the password segment of a URL: scheme://user:pass@host -> scheme://user:[REDACTED]@host.
pub fn mask_url_password(url: &str) -> String {
    let Some(scheme_end) = url.find("://") else {
        return url.to_string();
    };
    let rest = &url[scheme_end + 3..];
    let Some(at) = rest.find('@') else {
        return url.to_string();
    };
    let authority = &rest[..at];
    let Some(colon) = authority.find(':') else {
        return url.to_string();
    };
    let mut masked = String::with_capacity(url.len());
    masked.push_str(&url[..scheme_end + 3]);
    masked.push_str(&authority[..colon + 1]);
    masked.push_str("[REDACTED]");
    masked.push_str(&rest[at..]);
    masked
}

